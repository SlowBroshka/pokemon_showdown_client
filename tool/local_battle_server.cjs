// Development-only loopback harness using the official Showdown battle engine.
// SHOWDOWN_PATH must point to a built smogon/pokemon-showdown checkout.
const path = require('node:path');
const http = require('node:http');
const root = process.env.SHOWDOWN_PATH;
if (!root) throw new Error('Set SHOWDOWN_PATH to a built Showdown checkout');
const {BattleStream, getPlayerStreams, Teams} = require(path.join(root, 'dist/sim'));
const sockjs = require(path.join(root, 'node_modules/sockjs'));
const server = http.createServer();
const socketServer = sockjs.createServer({log() {}});
socketServer.on('connection', socket => {
  let room = 'battle-local';
  let streams;
  let revision = 0;
  let request;
  let rejected = false;
  const send = text => socket.write(`>${room}\n${text}`);
  socket.on('data', data => {
    if (['|/join battle-local', '|/join battle-local-force'].includes(data) && !streams) {
      room = data.slice(7);
      rejected = false;
      streams = getPlayerStreams(new BattleStream());
      send('|init|battle\n|title|Local practice');
      (async () => {
        for await (let chunk of streams.p1) {
          // rqid is server framing, not generated by the battle simulator.
          chunk = chunk.split('\n').map(line => {
            if (!line.startsWith('|request|')) return line;
            request = JSON.parse(line.slice(9));
            if (request) request.rqid = ++revision;
            return '|request|' + JSON.stringify(request);
          }).join('\n');
          send(chunk);
        }
      })().catch(() => socket.close());
      (async () => {
        for await (const chunk of streams.p2) {
          for (const line of chunk.split('\n')) {
            if (!line.startsWith('|request|')) continue;
            const r = JSON.parse(line.slice(9));
            if (!r || r.wait) continue;
            const choice = r.forceSwitch
              ? `switch ${r.side.pokemon.findIndex(p => !p.active && !p.condition.endsWith('fnt')) + 1}`
              : 'move 1';
            await streams.p2.write(choice);
          }
        }
      })().catch(() => socket.close());
      // Consume unused streams so the harness retains no unbounded transcripts.
      for (const name of ['omniscient', 'spectator', 'p3', 'p4']) {
        (async () => { for await (const _ of streams[name]) { /* drain */ } })().catch(() => {});
      }
      const team = (names, move) => Teams.pack(names.map(species => ({
        name: species, species, ability: 'No Ability', moves: [move],
        nature: 'Hardy', level: 50, teraType: 'Normal',
      })));
      const forced = room.endsWith('-force');
      const ownTeam = forced ? Teams.pack([
        {species: 'Magikarp', ability: 'No Ability', moves: ['splash'], level: 1},
        {species: 'Snorlax', ability: 'No Ability', moves: ['tackle'], level: 100},
      ]) : team(['Snorlax', 'Blissey'], 'tackle');
      streams.omniscient.write(`>start ${JSON.stringify({formatid: 'gen9customgame@@@!teampreview', seed: [1, 2, 3, 4]})}\n>player p1 ${JSON.stringify({name: 'LocalPlayer', team: ownTeam})}\n>player p2 ${JSON.stringify({name: 'LocalOpponent', team: team(['Blissey', 'Magikarp'], forced ? 'tackle' : 'splash')})}`);
    } else if (data === `${room}|/leave`) {
      send('|deinit');
      streams?.omniscient.writeEnd();
      streams = null;
    } else if (streams && data.startsWith(`${room}|/choose `)) {
      const [choice, rqid] = data.slice(`${room}|/choose `.length).split('|');
      if (Number(rqid) !== request?.rqid) {
        send('|error|[Unavailable choice] The local request changed');
      } else if (!rejected && process.env.LOCAL_REJECT_FIRST === '1') {
        rejected = true;
        send('|error|[Invalid choice] Local acceptance-test refusal');
      } else {
        streams.p1.write(choice);
      }
    }
  });
  socket.on('close', () => streams?.omniscient.writeEnd());
});
socketServer.installHandlers(server, {prefix: '/showdown'});
server.listen(8000, '127.0.0.1', () => console.log('Local engine harness: ws://127.0.0.1:8000/showdown/websocket; join battle-local'));
